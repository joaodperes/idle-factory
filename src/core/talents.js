export const TALENT_UNLOCK_LEVEL=5;
export const CAREER_CAPSTONE_COST=49;
export const MAX_FACTORY_LEVEL=110;
export const TIER_RULES=Object.freeze(Object.fromEntries(Array.from({length:10},(_,index)=>[index+1,{spent:index===9?49:index*5}])));
const EXPERIENCE=[0];
for(let level=1;level<MAX_FACTORY_LEVEL;level++)
  EXPERIENCE.push(EXPERIENCE.at(-1)+Math.ceil(60*Math.pow(1.14,level-1)+12*level));
export function factoryLevel(state){
 const xp=Math.max(0,state.xp||0);
 let lo=0,hi=EXPERIENCE.length;
 while(lo+1<hi){const mid=(lo+hi)>>1;if(EXPERIENCE[mid]<=xp)lo=mid;else hi=mid;}
 return lo+1;
}
export function nextFactoryLevelXp(state){const level=factoryLevel(state);return level>=MAX_FACTORY_LEVEL?null:EXPERIENCE[level];}
export function factoryLevelStartXp(level){return EXPERIENCE[Math.max(0,Math.min(MAX_FACTORY_LEVEL-1,level-1))];}
export function pointsEarned(state){return Math.max(0,factoryLevel(state)-TALENT_UNLOCK_LEVEL+1)+Math.max(0,state.legacyTalentCredits||0);}
export function talentPointsUsed(state){return Object.entries(TALENT_EFFECTS).reduce((sum,[id])=>sum+Math.max(0,state.talents?.[id]||0),0);}
export function freeTalentPoints(state){return Math.max(0,pointsEarned(state)-talentPointsUsed(state));}
export function talentModifier(state,key){return Object.entries(TALENT_EFFECTS).reduce((sum,[id,e])=>sum+(state.talents?.[id]||0)*(e[key]||0),0);}
export function findTalent(catalog,id){
 for(const [treeId,tree] of Object.entries(catalog.talents||{})){
   const node=tree.nodes.find(n=>n.id===id);
   if(node)return {treeId,tree,node};
 }
 return null;
}
export function completedCareers(state,catalog){
 const stored=new Set(state.completedCareers||[]);
 for(const [id,tree] of Object.entries(catalog.talents||{}))
  if(tree.nodes.some(node=>node.capstone&&(state.talents?.[node.id]||0)>0))stored.add(id);
 return [...stored];
}
export function currentCareer(state,catalog){
 const done=completedCareers(state,catalog);
 if(state.careerTree&&!done.includes(state.careerTree))return state.careerTree;
 const invested=Object.entries(catalog.talents||{}).find(([id,tree])=>!done.includes(id)&&tree.nodes.some(n=>(state.talents?.[n.id]||0)>0));
 return invested?.[0]||null;
}
export function talentStatus(state,catalog,id){
 const entry=findTalent(catalog,id);
 if(!entry)return {enabled:false,reason:'Unknown talent'};
 const {treeId,tree,node}=entry;
 if(factoryLevel(state)<TALENT_UNLOCK_LEVEL)return {enabled:false,reason:'Career talents unlock at Factory Level 5'};
 const chosen=currentCareer(state,catalog);
 if(chosen&&chosen!==treeId)return {enabled:false,reason:'Finish the '+catalog.talents[chosen].name+' capstone before entering another career'};
 if((state.talents[node.id]||0)>=node.max)return {enabled:false,reason:'Fully trained'};
 if(freeTalentPoints(state)<1)return {enabled:false,reason:'Earn another Factory Level for a talent point'};
 const spent=tree.nodes.reduce((sum,n)=>sum+(state.talents[n.id]||0),0);
 const needed=TIER_RULES[node.tier].spent;
 if(spent<needed)return {enabled:false,reason:'Spend '+(needed-spent)+' more point(s) in this career'};
 if(node.requires?.length&&!node.requires.some(parent=>(state.talents[parent]||0)>0))
   return {enabled:false,reason:'Requires an earlier connected talent'};
 return {enabled:true,reason:node.capstone?'Complete this career and open the next':'Ready to learn'};
}
export function refundTalents(state){state.talents={};state.careerTree=null;state.completedCareers=[];}
